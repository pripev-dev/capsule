/**
 * The public fidelity layer, and what it does and does not prove.
 *
 * **It proves page-composition fidelity.** Given the page the archived Claude
 * Design prototype composed, the ported ESM engine lays out the same six
 * surfaces and produces the same geometry, the same line spans, the same
 * pagination and the same validator findings - compared as raw bytes against the
 * files in `fixtures/synthetic-golden/`.
 *
 * **It does not prove durable-capsule validity, and it must not be read as
 * doing so.** The composer emits a *page composition*. `capsule.schema.json`
 * describes the durable *contract*, and the two are not the same document: the
 * contract additionally requires consent, people, recordings, preservation,
 * access, version and migration - everything a family needs to reconstruct a
 * capsule without us. Assembling that is **Gate 2's**, and Stage 5 of the port
 * is explicitly partial on it. The gap is pinned below in full rather than
 * summarised, so closing it fails loudly.
 *
 * The expectations were produced by the archived prototype, loaded through plain
 * `require` - not by the code under test. An expectation generated by the thing
 * being tested proves only that it agrees with itself.
 *
 * Everything here is synthetic, so it runs on a clean public clone.
 *
 * If a comparison fails, the port is wrong. Never adjust the expectation.
 *
 * The one exception is a DECIDED departure: the prototype got something wrong,
 * the engine now does it differently on purpose, and `departures.json` says
 * which surface, which blocks, when and why. The prototype's bytes stay in
 * `expected-surfaces.json` untouched; the surface is compared against the
 * departure's own record instead, and every block the departure does not name
 * must still be the prototype's, byte for byte.
 */
